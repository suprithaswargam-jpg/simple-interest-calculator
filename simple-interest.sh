# Contributing to Simple Interest Calculator

All contributions, bug reports, bug fixes, documentation improvements, enhancements, and ideas are welcome.

Please read this CONTRIBUTING guide before contributing.

## Code of Conduct
This project follows a Code of Conduct. Please read CODE_OF_CONDUCT.md. By participating, you are expected to uphold this code. Please report unacceptable behavior.

## How to Contribute

### Reporting Bugs / Issues
1. Check existing Issues to avoid duplicates.
2. Open a new Issue.
3. Describe the bug clearly: what you expected, what happened, steps to reproduce, screenshots, environment.
4. Use a clear title for the Issue.

### Suggesting Enhancements
1. Open an Issue for the enhancement.
2. Explain the use case and why it is needed.
3. Suggest the solution if possible.

### Pull Requests
1. Fork this repository.
2. Clone your forked repository:
   git clone https://github.com/suprithaswargam-jpg/simple-interest-calculator.git
3. Create a new branch for your changes:
   git checkout -b my-new-branch
4. Make your changes and test them.
5. Commit your changes:
   git add .
   git commit -m "Add my changes"
6. Push your branch:
   git push origin my-new-branch
7. Submit a Pull Request with a clear description of your changes.
8. Wait for review. Make requested changes if needed.

### First Time Contributors
- Fork, Clone, Branch, Commit, Push, Pull Request - follow the steps above.
- Keep Pull Requests small and focused.
- Update README.md if needed.

## Reporting Bugs
Use Issues to report bugs. Include steps to reproduce, expected behavior, actual behavior.

## Style Guidelines
- Write clear commit messages.
- Test your code before submitting.
- Follow existing code style.

Thank you for contributing!
